// node tools/captions.mjs  — validate every caption and write campaign/30-day-plan.md.
// A caption's length is counted in Unicode code points, spaces, line breaks and
// hashtags included (the brief's rule: fewer than 400). Fails (exit 1) on any
// caption at 400 or more, without hashtags, or without the site.
import { writeFileSync, existsSync } from 'node:fs'
import { POSTS, SITE } from '../campaign/posts.mjs'

const here = new URL('..', import.meta.url).pathname
const len = (s) => [...s].length
const bad = []
for (const p of POSTS) {
  p.captions.forEach((c, k) => {
    const n = len(c)
    if (n >= 400) bad.push(`day ${p.day} caption ${k + 1}: ${n} characters`)
    if (!/#\w/.test(c)) bad.push(`day ${p.day} caption ${k + 1}: no hashtags`)
    if (!c.includes(SITE)) bad.push(`day ${p.day} caption ${k + 1}: no ${SITE}`)
  })
  for (const e of p.evidence) if (!existsSync(here + e)) bad.push(`day ${p.day}: missing evidence ${e}`)
}

const md = [
  '# Zeta — first 30-day campaign',
  '',
  'Generated by `tools/captions.mjs` from `campaign/posts.mjs` — edit the data, then re-run; do not edit this file by hand.',
  'Every caption is counted in characters (Unicode code points, spaces, line breaks and hashtags included) and must be under 400.',
  '',
  '**Status.** `ready` — the evidence exists and every number shown is in `verification/verified-examples.md`. `verify-first` — capture and check the specific example before publishing.',
  '',
  '| Day | Week | Series | Topic | Format | Status |',
  '|---|---|---|---|---|---|',
  ...POSTS.map((p) => `| ${p.day} | ${p.week} | ${p.series} | ${p.topic} | ${p.format} | ${p.status} |`),
  '',
  'Days 29–30: review the numbers (watch time, saves, link clicks) and make two follow-ups from the best performer — see the brief §7.',
  '',
  ...POSTS.flatMap((p) => [
    `## Day ${p.day} — ${p.topic}`,
    '',
    `**Series:** ${p.series} · **Format:** ${p.format} · **Objective:** ${p.objective} · **Status:** \`${p.status}\``,
    '',
    `**Hook:** ${p.hook}`,
    '',
    `**Evidence:** ${p.evidence.length ? p.evidence.map((e) => `\`${e}\``).join(', ') : '_none yet — capture before production_'}`,
    '',
    ...p.captions.flatMap((c, k) => [`**${k === 0 ? 'Primary caption' : `Alternative ${k}`}** — ${len(c)} characters`, '', '```text', c, '```', '']),
  ]),
].join('\n')
writeFileSync(here + 'campaign/30-day-plan.md', md + '\n')
const counts = POSTS.flatMap((p) => p.captions.map(len))
console.log(`${POSTS.length} posts, ${counts.length} captions, ${Math.min(...counts)}–${Math.max(...counts)} characters`)
if (bad.length) { console.error(bad.join('\n')); process.exit(1) }
